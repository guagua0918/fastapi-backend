-- 足印評估：scan_session + footprint（fid → object.oid）
-- 在已連上 fastapi_dev 的 psql 執行

CREATE TABLE IF NOT EXISTS scan_session (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mid             integer NOT NULL REFERENCES member (id),
    created_at      timestamptz NOT NULL DEFAULT now(),
    status          text NOT NULL DEFAULT 'in_progress'
                    CHECK (status IN ('in_progress', 'completed', 'abandoned'))
);

CREATE TABLE IF NOT EXISTS footprint (
    fid             integer PRIMARY KEY REFERENCES object (oid),
    session_id      integer NOT NULL REFERENCES scan_session (id),
    mid             integer NOT NULL REFERENCES member (id),
    foot_side       text NOT NULL CHECK (foot_side IN ('left', 'right')),
    created_at      timestamptz NOT NULL DEFAULT now(),

    input_image_path       text,
    canvas_width           integer NOT NULL DEFAULT 1080,
    canvas_height          integer NOT NULL DEFAULT 1440,
    letterbox_fill         text NOT NULL DEFAULT 'white'
                           CHECK (letterbox_fill IN ('white', 'black')),

    sam_mask_path          text,
    pca_angle_deg          double precision,
    pca_aligned_mask_path  text,
    toe_cropped_mask_path  text,
    aligned_preview_path   text,

    processing_status      text NOT NULL DEFAULT 'pending'
        CHECK (processing_status IN (
            'pending', 'sam_done', 'pca_done', 'toe_cropped',
            'cv_keypoints_done', 'user_confirmed', 'cv_failed'
        )),
    processing_error_log   text,

    cv_a_x double precision, cv_a_y double precision,
    cv_b_x double precision, cv_b_y double precision,
    cv_c_x double precision, cv_c_y double precision,
    cv_d_x double precision, cv_d_y double precision,

    user_a_x double precision, user_a_y double precision,
    user_b_x double precision, user_b_y double precision,
    user_c_x double precision, user_c_y double precision,
    user_d_x double precision, user_d_y double precision,

    is_cv_available      boolean NOT NULL DEFAULT false,
    correction_distance  double precision,
    is_corrected         boolean,

    forefoot_width  double precision,
    arch_width      double precision,
    csi_value       double precision,
    is_flat         boolean,

    UNIQUE (session_id, foot_side)
);

CREATE INDEX IF NOT EXISTS ix_footprint_pending
    ON footprint (processing_status)
    WHERE processing_status = 'pending';

CREATE INDEX IF NOT EXISTS ix_scan_session_mid
    ON scan_session (mid);
